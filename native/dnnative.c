// "8b 05 ?? .." -> bytes + mask; returns the length
static int parseSig(const char *s, BYTE *b, BYTE *m, int cap)
{
    int n = 0;
    while (*s && n < cap) {
        if (*s == ' ') { s++; continue; }
        if (s[0] == '?') m[n] = 0, b[n] = 0;
        else { unsigned v; sscanf_s(s, "%2x", &v); b[n] = (BYTE)v, m[n] = 1; }
        n++, s += 2;
    }
    return n;
}

// unique match of a signature in [t, t+len), or NULL (none or several)
static BYTE *findSig(BYTE *t, size_t len, const char *sig)
{
    BYTE b[128], m[128];
    int n = parseSig(sig, b, m, 128), k0 = 0;
    while (k0 < n && !m[k0]) k0++;
    if (k0 == n || len < (size_t)n) return NULL;
    BYTE *hit = NULL, *p = t + k0, *end = t + len - n + k0 + 1;
    while ((p = memchr(p, b[k0], end - p)) != NULL) {
        BYTE *s = p - k0;
        int k = k0 + 1;
        while (k < n && (!m[k] || s[k] == b[k])) k++;
        if (k == n) {
            if (hit) return NULL;
            hit = s;
        }
        p++;
    }
    return hit;
}

// 1 = every signature found once; logs the first missing one
static int resolveSigs(BYTE *base)
{
    IMAGE_NT_HEADERS *nt = (IMAGE_NT_HEADERS *)(base + ((IMAGE_DOS_HEADER *)base)->e_lfanew);
    IMAGE_SECTION_HEADER *sec = IMAGE_FIRST_SECTION(nt), *text = NULL;
    for (int i = 0; i < nt->FileHeader.NumberOfSections; i++)
        if (!memcmp(sec[i].Name, ".text", 6)) text = &sec[i];
    if (!text) { dnlog("sigs: no .text section"); return 0; }
    BYTE *t = base + text->VirtualAddress;
    size_t len = text->Misc.VirtualSize;
    for (int i = 0; i < S_COUNT; i++) {
        const Sig *s = &g_sigs[i];
        BYTE *hit = findSig(t, len, s->sig);
        if (!hit) {
            char msg[128];
            _snprintf_s(msg, sizeof msg, _TRUNCATE, "sigs: %s not found once (native features off)", s->name);
            dnlog(msg);
            return 0;
        }
        g_addr[i] = s->refAt < 0 ? (uintptr_t)hit : (uintptr_t)(hit + s->insnEnd + *(int32_t *)(hit + s->dispAt));
    }
    return 1;
}

